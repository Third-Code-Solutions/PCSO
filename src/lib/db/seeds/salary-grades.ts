export function buildSalaryGradeSeeds(): SalaryGradeSeed[] {
  const seeds: SalaryGradeSeed[] = [];

  for (let grade = 1; grade <= 33; grade++) {
    const steps = SSL_V_2024[grade];
    if (!steps) continue;

    for (let stepIdx = 0; stepIdx < 8; stepIdx++) {
      const salary = steps[stepIdx];
      if (salary === undefined) continue;

      seeds.push({
        grade,
        step: stepIdx + 1,
        monthlySalary: salary.toFixed(2),
        effectiveDate: EFFECTIVE_DATE,
      });
    }
  }

  return seeds;
}
